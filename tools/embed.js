// embed.js -- packs compiled SPIR-V files into src/spv_embedded.h
// usage: node tools/embed.js <spvDir> <outHeader>
'use strict';
const fs = require('fs');
const path = require('path');

const dir = process.argv[2] || 'build/spv';
const out = process.argv[3] || 'src/spv_embedded.h';

if (!fs.existsSync(dir)) {
    console.error('embed.js: no such directory: ' + dir);
    process.exit(1);
}
const files = fs.readdirSync(dir).filter(f => f.endsWith('.spv')).sort();
if (files.length === 0) {
    console.error('embed.js: no .spv files in ' + dir);
    process.exit(1);
}

let header = '// Generated by tools/embed.js from build/spv/*.spv -- do not edit.\n';
header += '#pragma once\n#include <cstdint>\n#include <cstring>\n\n';

let table = '';
let totalBytes = 0;
for (const f of files) {
    const name = path.basename(f, '.spv');
    const id = name.replace(/[^A-Za-z0-9_]/g, '_');
    const buf = fs.readFileSync(path.join(dir, f));
    if (buf.length === 0 || buf.length % 4 !== 0) {
        console.error('embed.js: ' + f + ' is not a valid SPIR-V word stream');
        process.exit(1);
    }
    const words = buf.length / 4;
    const lines = [];
    for (let i = 0; i < words; i += 8) {
        const row = [];
        for (let j = i; j < Math.min(i + 8, words); ++j) {
            row.push('0x' + buf.readUInt32LE(j * 4).toString(16).padStart(8, '0') + 'u');
        }
        lines.push('    ' + row.join(', ') + ',');
    }
    header += 'static const uint32_t spv_' + id + '[] = {\n' + lines.join('\n') + '\n};\n\n';
    table += '    { "' + name + '", spv_' + id + ', ' + buf.length + 'u },\n';
    totalBytes += buf.length;
}

header += 'struct SpvEntry { const char* name; const uint32_t* data; uint32_t sizeBytes; };\n\n';
header += 'static const SpvEntry kSpvTable[] = {\n' + table + '};\n\n';
header += 'static inline const SpvEntry* spvFind(const char* want)\n{\n';
header += '    for (const SpvEntry& e : kSpvTable) {\n';
header += '        if (std::strcmp(e.name, want) == 0) return &e;\n';
header += '    }\n';
header += '    return nullptr;\n}\n';

fs.writeFileSync(out, header);
console.log('embed.js: embedded ' + files.length + ' shaders (' + totalBytes + ' bytes) -> ' + out);
